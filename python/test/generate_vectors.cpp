// Generates python/test/vectors.txt: the bytes the C++ library produces for a
// fixed set of values under each option combination the Python wrapper
// supports, so test_pyalpaca.py can check that pyalpaca.serialize() is
// byte-identical to alpaca::serialize<O>() and that pyalpaca.deserialize()
// reads what C++ wrote. Build & run from the repo root:
//   c++ -std=c++20 -I include python/test/generate_vectors.cpp -o gen && ./gen
//   > python/test/vectors.txt
#include <alpaca/alpaca.h>
#include <array>
#include <cstdio>
#include <map>
#include <string>
#include <vector>

// format string: "?cbBhHiIqQfds[i][3B]{s:i}(cif)"
struct Everything {
  bool a;
  char b;
  int8_t c;
  uint8_t d;
  int16_t e;
  uint16_t f;
  int32_t g;
  uint32_t h;
  int64_t i;
  uint64_t j;
  float k;
  double l;
  std::string m;
  std::vector<int32_t> n;
  std::array<uint8_t, 3> o;
  std::map<std::string, int32_t> p;
  std::tuple<char, int32_t, float> q;
};

static const Everything VALUE{true,
                              'x',
                              -5,
                              200,
                              -1234,
                              54321,
                              -100000,
                              3000000000u,
                              -5000000000ll,
                              10000000000ull,
                              1.5f,
                              -2.25,
                              "hello",
                              {1, -2, 300},
                              {7, 8, 9},
                              {{"a", 1}, {"b", 2}},
                              {'z', 42, 0.5f}};

template <alpaca::options O> void emit(const char *name) {
  std::vector<uint8_t> bytes;
  alpaca::serialize<O>(VALUE, bytes);
  std::printf("%s ", name);
  for (auto b : bytes) {
    std::printf("%02x", b);
  }
  std::printf("\n");
}

int main() {
  using alpaca::options;
  std::printf("# generated by python/test/generate_vectors.cpp; <options name> "
              "<hex bytes>\n");
  std::printf("# format: ?cbBhHiIqQfds[i][3B]{s:i}(cif)\n");
  emit<options::none>("none");
  emit<options::big_endian>("big_endian");
  emit<options::fixed_length_encoding>("fixed_length_encoding");
  emit<options::big_endian | options::fixed_length_encoding>(
      "big_endian|fixed_length_encoding");
  emit<options::with_checksum>("with_checksum");
  emit<options::fixed_length_encoding | options::with_checksum>(
      "fixed_length_encoding|with_checksum");
  emit<options::big_endian | options::fixed_length_encoding |
       options::with_checksum>(
      "big_endian|fixed_length_encoding|with_checksum");
  return 0;
}
